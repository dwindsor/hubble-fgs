package ops

const (
	MSG_OP_UNDEF = 0
	// The following events generate MsgTcpConnectUnix type events.

	// MSG_OP_TCPCONNECT event indicates a TCP connect() syscall
	// has been started. The event is generated on entry into a connect() call
	// and includes the info listed in `MsgTcpConnect`. It does _not_
	// imply the connect call will be successful and the 'Return' field
	// is undefined at this point. The event is disabled by default users
	// should use TCPCONNECTRET events which populate the 'Return' field.
	// The other fields `Kube`, `Common`, and `PID' will be populated using
	// data stored from exec() call of the associated pid.
	MSG_OP_TCPCONNECT = 1
	// MSG_OP_IPV5_TCPCONNECTRET event indicates a connect() syscall has
	// returned. The event populates the `MsgTcpConnect` and `Return`
	// codes. If the call is an asynchronous call the `Return` code will
	// indicate this. The other fields `Kube`, `Common`, and `PID' will
	// be populated using data stored from exec() call of the associated pid.
	MSG_OP_TCPCONNECTRET = 2
	// MSG_OP_BIND event indicates a bind() syscall has been issued.
	// This hook is placed behind the syscall in order to account for
	// kernel side generating ports and IP addresses when user does not
	// provide them. This event is not generated by default. By default
	// the bind() information is stored and only returned when the process
	// issues a subsequent listen() call. The other fields `Kube`, `Common`,
	// and `PID' will be populated using data stored from exec() call of
	// the associated pid.
	MSG_OP_BIND = 3
	// MSG_OP_LISTEN event indicates a listen() syscall has been issued.
	// This hook will generate an event including the information stored
	// from previous exec call and bind call.
	MSG_OP_LISTEN = 4
	// MSG_OP_EXECVE event indicates a process was created. The 'PID'
	// and 'Common' fields will be populated. This event is positioned
	// after exec() calls have been validated so failed syscalls will
	// not be reported. To generate events provide the '-e' option to
	// hubble-fgs, without the option the hook only populates the data
	// store for later use by above events.
	MSG_OP_EXECVE = 5

	MSG_OP_TLS = 6

	MSG_OP_EXIT = 7

	MSG_OP_TCPCLOSE = 8

	MSG_OP_ACCEPT = 9

	MSG_OP_CRED = 10

	MSG_OP_KFREE_SKB = 11

	MSG_OP_TLS_CONT = 12

	MSG_OP_GENERIC_KPROBE     = 13
	MSG_OP_GENERIC_TRACEPOINT = 14

	// MSG_OP_TCPSTATS event report socket stats for TCP sockets.
	MSG_OP_TCPSTATS = 15

	MSG_OP_HTTP = 16

	MSG_OP_UDPCLOSE   = 17
	MSG_OP_UDPCONNECT = 18
	MSG_OP_UDPSTATS   = 19

	MSG_OP_INTERFACE_STATS = 20

	MSG_OP_UDPPAYLOAD = 21

	MSG_OP_PROCESS_NETWORK_BURST = 22

	// MSG_OP_CLONE notifies user-space that a clone() event has occurred.
	MSG_OP_CLONE = 23

	MSG_OP_DATA = 24

	// MSG_OP_EXIT event indicates a network namespace is being destroyed.
	MSG_OP_NETNS_EXIT = 25

	// just for testing
	MSG_OP_TEST = 254

	// for user space payload parsers
	MSG_OP_DNS = 128

	MSG_OP_FILE = 129

	MSG_OP_IP_ERROR = 130
)

type OpCode int

const (
	MsgOpUndef               = iota
	MsgOpTCPConnect          = 1
	MsgOpTCPConnectReturn    = 2
	MsgOpBind                = 3
	MsgOpListen              = 4
	MsgOpExecve              = 5
	MsgOpTLS                 = 6
	MsgOpExit                = 7
	MsgOpTCPClose            = 8
	MsgOpAccept              = 9
	MsgOpCred                = 10
	MsgOpKfreeSkb            = 11
	MsgOpTLSCont             = 12
	MsgOpGenericKprobe       = 13
	MsgOpGeneric_Tracepoint  = 14
	MsgOpTCPStats            = 15
	MsgOpHTTP                = 16
	MsgOpUDPClose            = 17
	MsgOpUDPConnect          = 18
	MsgOpUDPStats            = 19
	MsgOpInterfaceStats      = 20
	MsgOpUDPPayload          = 21
	MsgOpProcessNetworkBurst = 22
	MsgOpClone               = 23
	MsgOpData                = 24
	MsgOpNetnsExit           = 25
	MsgOpTest                = 254
	MsgOpDNS                 = 128
	MsgOpFile                = 129
	MsgOpIpError             = 130
)

func (op OpCode) String() string {
	opCodeMap := map[OpCode]string{
		MsgOpUndef:               "Undef",
		MsgOpTCPConnect:          "TCPConnect",
		MsgOpTCPConnectReturn:    "TCPConnectReturn",
		MsgOpBind:                "TCPBind",
		MsgOpListen:              "TCPListen",
		MsgOpExecve:              "Execve",
		MsgOpTLS:                 "TLS",
		MsgOpExit:                "Exit",
		MsgOpTCPClose:            "TCPClose",
		MsgOpAccept:              "TCPAccept",
		MsgOpCred:                "Cred",
		MsgOpKfreeSkb:            "KfreeSkb",
		MsgOpTLSCont:             "TLSCont",
		MsgOpGenericKprobe:       "GenericKprobe",
		MsgOpGeneric_Tracepoint:  "GenericTracepoint",
		MsgOpTCPStats:            "TCPStats",
		MsgOpHTTP:                "HTTP",
		MsgOpUDPClose:            "UDPClose",
		MsgOpUDPConnect:          "UDPConnect",
		MsgOpUDPStats:            "UDPStats",
		MsgOpInterfaceStats:      "InterfaceStats",
		MsgOpUDPPayload:          "UDPPayload",
		MsgOpProcessNetworkBurst: "ProcessNetworkBurst",
		MsgOpClone:               "Clone",
		MsgOpData:                "Data",
		MsgOpNetnsExit:           "NetNsExit",
		MsgOpTest:                "Test",
		MsgOpDNS:                 "DNS",
		MsgOpFile:                "File",
		MsgOpIpError:             "IPError",
	}
	if val, ok := opCodeMap[op]; ok {
		return val
	}
	return "undefOpCode"
}
