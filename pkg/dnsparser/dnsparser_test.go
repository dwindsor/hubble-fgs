			for _, ip := range tq.wantIPs {
				wantIPMaps[binary.BigEndian.Uint32(ip.AsSlice())] = tq.wantDomain
			}

			actualIP, err := ipMap.Values()
			if err != nil {
				t.Fatalf("failed to retrieve values out of IP map: %s", err)
			}

			if len(actualIP) != len(wantIPMaps) {
				t.Errorf("len(got) %d != len(want) %d", len(actualIP), len(wantIPMaps))
				t.FailNow()
			}

			if !maps.Equal(actualIP, wantIPMaps) {
				t.Errorf("got %v, expected %v", actualIP, wantIPMaps)
				if len(actualIP) > 0 && len(wantIPMaps) > 0 {
					actualValues := slices.Collect(maps.Values(actualIP))
					wantValues := slices.Collect(maps.Values(wantIPMaps))
					t.Errorf("domain: got %v, expected %v", []byte(actualValues[0]), []byte(wantValues[0]))
				}
			}
