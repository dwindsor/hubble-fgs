var verifierLogs = flag.Bool("verlogs", false, "Write the full verifier logs in the ./verifier.log file")

func parseIPs(ips ...string) []netip.Addr {
	netIPs := []netip.Addr{}
	for _, ip := range ips {
		netIPs = append(netIPs, netip.MustParseAddr(ip))
	}
	return netIPs
}

func loadDNSTestCollection(t *testing.T) *ebpf.Collection {
	// Try at least loading the test program from 5.15, even if it cannot run it should load.
	if v := "5.15.0"; !kernels.MinKernelVersion(v) {
		t.Skipf("Minimum kernel version (%v) not met, skipping", v)
	}

	// load test program
	collSpec, err := ebpf.LoadCollectionSpec(filepath.Join("../../bpf/tests/objs", objName))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			t.Fatalf("please run 'make tetragon-bpf-test' to compile the BPF test program: %s", err)
		}
		t.Fatal(err)
	}
	collOpts := ebpf.CollectionOptions{}
	if verifierLogs != nil && *verifierLogs {
		collOpts.Programs = ebpf.ProgramOptions{
			LogLevel: ebpf.LogLevelInstruction,
		}
	}
	coll, err := ebpf.NewCollectionWithOptions(collSpec, collOpts)
	if err != nil {
		var ve *ebpf.VerifierError
		if errors.As(err, &ve) {
			t.Fatalf("verifier error: %+v\n", ve)
		}
		t.Fatal(err)
	}
	t.Cleanup(func() {
		coll.Close()
	})

	prog, ok := coll.Programs[programName]
	if !ok {
		t.Fatalf("%s not found", programName)
	}

	if verifierLogs != nil && *verifierLogs {
		logFile, err := os.Create("verifier.log")
		if err != nil {
			t.Fatal(err)
		}

		_, err = logFile.WriteString(prog.VerifierLog)
		if err != nil {
			t.Fatal(err)
		}
		logFile.Close()
	}

	// Direct packet access with BPF_PROG_TYPE_CGROUP_SKB in BPF_PROG_TEST_RUN needs
	// https://lore.kernel.org/r/20241125152603.375898-1-mahe.tardy@gmail.com
	if v := "6.13.0"; !kernels.MinKernelVersion(v) {
		t.Skipf("DNS parser test prog loads but cannot run: minimum kernel version (%v) not met, skipping", v)
	}

	return coll
}

