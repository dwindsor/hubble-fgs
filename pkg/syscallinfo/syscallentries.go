type MissingSyscalls struct {
	Calls []string
}

func (e *MissingSyscalls) Error() string {
	return fmt.Sprintf("some syscalls were missing: %s", strings.Join(e.Calls, ","))
}

// SyscallNamesToEntries attempts to translate a list of system call names to a list of entries,
// i.e., their implementation in the kernel.
// Each syscall name is expected to start with "sys_"
// Entries that do not start with "sys_" will be left unchanged
// MissingSyscalls is returned to indicate that no entries were found for a given syscall
func SyscallNamesToEntries(names []string) ([]string, error) {
	list, err := ftrace.ReadAvailFuncs("sys_")
	if err != nil {
		return nil, err
	}

	availMap := make(map[string]struct{}, len(list))
	for _, x := range list {
		availMap[x] = struct{}{}
	}

	ret := []string{}
	missingCalls := []string{}
	for _, name := range names {
		if !strings.HasPrefix(name, "sys_") {
			// if something does not start with sys_, add it as is
			ret = append(ret, name)
			continue
		}

		var entries []string
		if runtime.GOARCH == "amd64" {
			entries, _ = kernelSyscallEntriesX86[name]
			// add the default name as well if it does not exist in the list
			if e, err := arch.AddSyscallPrefix(name); err == nil {
				if !slices.Contains(entries, e) {
					entries = append(entries, e)
				}
			}
		} else {
			// for non-amd64, we do not have detailed information so just add the
			// the default name
			sym, err := arch.AddSyscallPrefix(name)
			if err != nil {
				return nil, fmt.Errorf("failed to add prefix to syscall %s: %w", sym, err)
			}
			entries = []string{sym}
		}

		// filter through available functions
		filtered := []string{}
		for _, e := range entries {
			if _, ok := availMap[e]; ok {
				filtered = append(filtered, e)
			}
		}

		if len(filtered) == 0 {
			missingCalls = append(missingCalls, name)
		} else {
			ret = append(ret, filtered...)
		}
	}

	if len(missingCalls) > 0 {
		err = &MissingSyscalls{Calls: missingCalls}
	}

	return ret, err
}
